"""Append a human-written example to eval/intent_dataset.csv.

  python eval/add_intent_example.py "ma ke ki 2ta napa deya jabe" medical banglish heldout
  python eval/add_intent_example.py "How do I print the passport?" app en train

label: app | medical | emergency.   lang: bn | en | banglish.   split: train | heldout.
Held-out rows must be written by a person (never generated by an LLM): they decide whether the
classifier may be switched on. LLM paraphrases may go to the TRAIN split only, with --synthetic,
and are marked source=synthetic.
"""
from __future__ import annotations

import argparse
import csv
from pathlib import Path

DATASET = Path(__file__).resolve().parent / "intent_dataset.csv"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("text")
    ap.add_argument("label", choices=["app", "medical", "emergency"])
    ap.add_argument("lang", choices=["bn", "en", "banglish"])
    ap.add_argument("split", choices=["train", "heldout"])
    ap.add_argument("--synthetic", action="store_true", help="an LLM paraphrase (train split only)")
    ap.add_argument("--author", default="team", help="who wrote it, e.g. a team member's initials")
    a = ap.parse_args()
    if a.synthetic and a.split != "train":
        ap.error("synthetic examples may only go to the train split")
    text = " ".join(a.text.split())
    with DATASET.open(encoding="utf-8") as f:
        if any(r["text"] == text for r in csv.DictReader(f)):
            ap.error("this text is already in the dataset")
    with DATASET.open("a", encoding="utf-8", newline="") as f:
        csv.writer(f).writerow([text, a.label, a.lang, "synthetic" if a.synthetic else f"human:{a.author}", a.split])
    print(f"added ({a.label}, {a.split})")


if __name__ == "__main__":
    main()
